    std::string fixture (const std::string& name)
    {
        const juce::File file { juce::String (std::string (WFG_TEST_FIXTURES_DIR))
                                  + "/documents/" + juce::String (name) };

        REQUIRE_MESSAGE (file.existsAsFile(), "missing fixture: " << file.getFullPathName());

        /*  Read as bytes and normalise, so a checkout that turned the fixture
            into CRLF tests the same thing as one that did not. The WRITER's
            line endings are pinned separately, below — that is the property
            that actually matters. */
        juce::MemoryBlock block;
        file.loadFileAsData (block);

        std::string text { static_cast<const char*> (block.getData()), block.getSize() };

        std::string out;
        out.reserve (text.size());

        for (const char c : text)
            if (c != '\r')
                out.push_back (c);

        return out;
    }

    ShowDocument loaded (const std::string& fixtureName)
    {
        ShowDocument document;
        const auto result = CanonicalXml::read (fixture (fixtureName), document);

        for (const auto& problem : result.problems)
            INFO (problem);

        REQUIRE (result.ok);
        return document;
    }
